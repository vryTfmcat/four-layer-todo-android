export function resolveLocale(setting: LanguageSetting, obsidianLanguage: string): AppLocale {
  if (setting !== "auto") return setting;
  return obsidianLanguage.toLowerCase().startsWith("zh") ? "zh" : "en";
}

let activeLocale: AppLocale = "zh";

export function setActiveLocale(locale: AppLocale): void {
  activeLocale = locale;
}

export function getActiveLocale(): AppLocale {
  return activeLocale;
}

export function tr(text: string, values: Record<string, string | number> = {}): string {
  const translated = activeLocale === "en" ? (ENGLISH[text] ?? text) : text;
  return translated.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function translateGuidedWorkspace<T>(value: T): T {
  if (activeLocale !== "en") return value;
  const visit = (item: unknown, key?: string): unknown => {
    if (typeof item === "string") {
      if (key === "source" || key === "kind") return item;
      return tr(item);
    }
    if (Array.isArray(item)) return item.map((entry) => visit(entry));
    if (item && typeof item === "object") {
      return Object.fromEntries(
        Object.entries(item).map(([entryKey, entryValue]) => [entryKey, visit(entryValue, entryKey)]),
      );
    }
    return item;
  };
  return visit(value) as T;
}
